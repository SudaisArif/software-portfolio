const slug = (s: string) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
const make = (rows: Row[], fact: string): Answer[] =>
  rows.map(([name, tier, aliases, detail]) => ({
    id: slug(name),
    name,
    tier,
    aliases: (aliases || "").split(";").filter(Boolean),
    fact: detail || fact,
  }));
